def get_invoice_pdf_context(invoice):
    """Build unified context dictionary for invoice PDF generation."""
    from .views import number_to_indian_currency_words
    from .invoice_qr import generate_invoice_qr_bundle

    profile = getattr(invoice.distributor, 'profile', None) if invoice.distributor else None
    business_name = getattr(profile, 'business_name', None) or 'Advance Billing Agency'
    business_phone = getattr(profile, 'phone', None) or '+91 98765 43210'
    business_address = getattr(profile, 'address', None) or 'Commercial Hub, Business Park, Phase II'
    business_gstin = getattr(profile, 'gstin', None) or '27AABCU9603R1ZM'
    upi_id = getattr(profile, 'upi_id', None) or 'advancebilling@upi'

    try:
        bundle = generate_invoice_qr_bundle(invoice)
        qr_base64 = bundle['qr_base64']
        qr_bytes = bundle['png_bytes']
    except Exception:
        qr_base64 = invoice.qr_code_base64
        qr_bytes = None

    tax_amt = float(invoice.tax_amount or 0.0)
    cgst_amount = round(tax_amt / 2, 2)
    sgst_amount = round(tax_amt / 2, 2)
    grand_total_words = number_to_indian_currency_words(invoice.grand_total)

    return {
        'invoice': invoice,
        'items': invoice.items.all(),
        'upi_id': upi_id,
        'business_name': business_name,
        'business_phone': business_phone,
        'business_address': business_address,
        'business_gstin': business_gstin,
        'qr_base64': qr_base64,
        'qr_bytes': qr_bytes,
        'cgst_amount': cgst_amount,
        'sgst_amount': sgst_amount,
        'grand_total_words': grand_total_words,
    }


def render_invoice_to_pdf_xhtml2pdf(invoice, template_name='billing/invoice_pdf.html'):
    """
    Generate PDF bytes using xhtml2pdf from the HTML/CSS invoice template.
    """
    if not pisa:
        raise RuntimeError("xhtml2pdf is not installed on the system.")

    context = get_invoice_pdf_context(invoice)
    template = get_template(template_name)
    html_content = template.render(context)

    pdf_buffer = io.BytesIO()
    pisa_status = pisa.CreatePDF(
        src=html_content,
        dest=pdf_buffer,
        encoding='utf-8'
    )

    if pisa_status.err:
        raise RuntimeError(f"xhtml2pdf rendering error: status={pisa_status.err}")

    return pdf_buffer.getvalue()


class NumberedCanvas(canvas.Canvas):
    """Two-pass canvas to dynamically compute and print total page numbers."""
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_number(num_pages)
            canvas.Canvas.showPage(self)
        canvas.Canvas.save(self)

    def draw_page_number(self, page_count):
        self.saveState()
        self.setFont("Helvetica", 8)
        self.setFillColor(colors.HexColor('#94a3b8'))
        footer_text = f"Generated by Advance Billing System • Certified Tax Invoice with Verified QR • Page {self._pageNumber} of {page_count}"
        self.drawCentredString(A4[0] / 2.0, 10 * mm, footer_text)
        self.restoreState()


def render_invoice_to_pdf_reportlab(invoice):
    """
    Generate PDF bytes using ReportLab direct Flowable elements and table layouts.
    """
    if not REPORTLAB_AVAILABLE:
        raise RuntimeError("ReportLab is not installed on the system.")

    context = get_invoice_pdf_context(invoice)
    pdf_buffer = io.BytesIO()

    doc = SimpleDocTemplate(
        pdf_buffer,
        pagesize=A4,
        leftMargin=12 * mm,
        rightMargin=12 * mm,
        topMargin=12 * mm,
        bottomMargin=16 * mm
    )

    styles = getSampleStyleSheet()
    primary_color = colors.HexColor('#4f46e5')
    dark_slate = colors.HexColor('#0f172a')
    muted_slate = colors.HexColor('#64748b')
    light_bg = colors.HexColor('#f8fafc')
    border_color = colors.HexColor('#e2e8f0')

    title_style = ParagraphStyle(
        'CompanyTitle',
        parent=styles['Normal'],
        fontName='Helvetica-Bold',
        fontSize=15,
        leading=18,
        textColor=dark_slate
    )
    subtitle_style = ParagraphStyle(
        'CompanySubtitle',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=8.5,
        leading=12,
        textColor=muted_slate
    )
    inv_title_style = ParagraphStyle(
        'InvoiceTitle',
        parent=styles['Normal'],
        fontName='Helvetica-Bold',
        fontSize=16,
        leading=18,
        textColor=primary_color,
        alignment=2  # Right
    )
    inv_meta_style = ParagraphStyle(
        'InvoiceMeta',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=8.5,
        leading=12,
        textColor=muted_slate,
        alignment=2  # Right
    )
    table_header_style = ParagraphStyle(
        'TableHeader',
        parent=styles['Normal'],
        fontName='Helvetica-Bold',
        fontSize=8.5,
        leading=10,
        textColor=colors.white
    )
    cell_style = ParagraphStyle(
        'TableCell',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=8.5,
        leading=11,
        textColor=dark_slate
    )
    cell_bold_style = ParagraphStyle(
        'TableCellBold',
        parent=styles['Normal'],
        fontName='Helvetica-Bold',
        fontSize=8.5,
        leading=11,
        textColor=dark_slate
    )
    words_style = ParagraphStyle(
        'WordsStyle',
        parent=styles['Normal'],
        fontName='Helvetica-Bold',
        fontSize=8.5,
        leading=11,
        textColor=colors.HexColor('#1e1b4b')
    )

    story = []

    # 1. Decorative accent line
    story.append(HRFlowable(width="100%", thickness=3, color=primary_color, spaceBefore=0, spaceAfter=8))

    # 2. Header: Company Info (Left) and TAX INVOICE block (Right)
    comp_p = Paragraph(f"<b>{context['business_name']}</b>", title_style)
    comp_sub = Paragraph(
        f"{context['business_address']}<br/>"
        f"Phone: {context['business_phone']} • UPI ID: {context['upi_id']}<br/>"
        f"<b>GSTIN: {context['business_gstin']}</b>",
        subtitle_style
    )

    status_color = '#15803d' if invoice.payment_status == 'PAID' else '#b45309'
    inv_p = Paragraph("TAX INVOICE", inv_title_style)
    inv_sub = Paragraph(
        f"<b>#{invoice.invoice_number}</b><br/>"
        f"Date: {invoice.created_at.strftime('%d %b, %Y %I:%M %p')}<br/>"
        f"<font color='{status_color}'><b>Status: {invoice.payment_status}</b></font>",
        inv_meta_style
    )

    header_table = Table([[ [comp_p, Spacer(1, 2), comp_sub], [inv_p, Spacer(1, 2), inv_sub] ]], colWidths=[105 * mm, 81 * mm])
    header_table.setStyle(TableStyle([
        ('VALIGN', (0, 0), (-1, -1), 'TOP'),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 6),
    ]))
    story.append(header_table)
    story.append(Spacer(1, 4))

    # 3. Customer Info and Logistics Table
    cust = invoice.customer
    cust_text = (
        f"<b>BILLED TO (CUSTOMER DETAILS)</b><br/>"
        f"<b>{invoice.customer_name}</b><br/>"
        f"Contact: {invoice.customer_phone}<br/>"
    )
    if cust and cust.address:
        cust_text += f"Address: {cust.address}" + (f", {cust.city}" if cust.city else "") + "<br/>"
    if cust and cust.gstin:
        cust_text += f"<b>Customer GSTIN: {cust.gstin}</b>"

    logistics_text = (
        f"<b>INVOICE &amp; PAYMENT LOGISTICS</b><br/>"
        f"Payment Instrument: {invoice.payment_method}<br/>"
        f"Merchant UPI ID: {context['upi_id']}<br/>"
        f"Place of Supply: Maharashtra (State Code 27)<br/>"
        f"Reverse Charge (RCM): No • Currency: INR (Rs.)"
    )

    party_table = Table([
        [Paragraph(cust_text, cell_style), Paragraph(logistics_text, cell_style)]
    ], colWidths=[93 * mm, 93 * mm])
    party_table.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, -1), light_bg),
        ('BOX', (0, 0), (-1, -1), 0.75, border_color),
        ('INNERGRID', (0, 0), (-1, -1), 0.5, border_color),
        ('PADDING', (0, 0), (-1, -1), 6),
        ('VALIGN', (0, 0), (-1, -1), 'TOP'),
    ]))
    story.append(party_table)
    story.append(Spacer(1, 6))

    # 4. Itemized Line Items Table
    item_rows = [
        [
            Paragraph("<b>#</b>", table_header_style),
            Paragraph("<b>Product / Service Description</b>", table_header_style),
            Paragraph("<para align='center'><b>Qty</b></para>", table_header_style),
            Paragraph("<para align='right'><b>Rate (Rs.)</b></para>", table_header_style),
            Paragraph("<para align='right'><b>Tax</b></para>", table_header_style),
            Paragraph("<para align='right'><b>Amount (Rs.)</b></para>", table_header_style),
        ]
    ]

    for idx, item in enumerate(context['items'], 1):
        item_rows.append([
            Paragraph(str(idx), cell_style),
            Paragraph(f"<b>{item.product_name}</b><br/><font size='7' color='#64748b'>HSN/SAC: 8471 • Standard Inventory</font>", cell_style),
            Paragraph(f"<para align='center'><b>{item.quantity}</b></para>", cell_style),
            Paragraph(f"<para align='right'>Rs. {item.unit_price:.2f}</para>", cell_style),
            Paragraph(f"<para align='right'>{item.tax_rate:.0f}%</para>", cell_style),
            Paragraph(f"<para align='right'><b>Rs. {item.total:.2f}</b></para>", cell_bold_style),
        ])

    items_table = Table(item_rows, colWidths=[10 * mm, 78 * mm, 18 * mm, 26 * mm, 20 * mm, 34 * mm])
    t_style = [
        ('BACKGROUND', (0, 0), (-1, 0), dark_slate),
        ('ALIGN', (0, 0), (-1, -1), 'LEFT'),
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 5),
        ('TOPPADDING', (0, 0), (-1, -1), 5),
        ('GRID', (0, 0), (-1, -1), 0.5, border_color),
    ]
    for r_idx in range(1, len(item_rows)):
        if r_idx % 2 == 0:
            t_style.append(('BACKGROUND', (0, r_idx), (-1, r_idx), light_bg))
    items_table.setStyle(TableStyle(t_style))
    story.append(items_table)
    story.append(Spacer(1, 6))

    # 5. Summary & QR Code Section
    qr_img_flowable = None
    if context.get('qr_bytes'):
        qr_io = io.BytesIO(context['qr_bytes'])
        qr_img_flowable = RLImage(qr_io, width=28 * mm, height=28 * mm)
    elif context.get('qr_base64'):
        try:
            b64_str = context['qr_base64'].split(',')[-1]
            qr_io = io.BytesIO(base64.b64decode(b64_str))
            qr_img_flowable = RLImage(qr_io, width=28 * mm, height=28 * mm)
        except Exception:
            qr_img_flowable = None

    qr_desc = (
        f"<para align='center'>"
        f"<font size='7' color='#059669'><b>[ DIGITALLY VERIFIED QR INVOICE ]</b></font><br/>"
        f"<font size='6.5' color='#64748b'>Scan with GPay, PhonePe, Paytm, BHIM<br/>"
        f"Encodes #{invoice.id} • Rs. {invoice.grand_total:.2f} • {invoice.customer_name}</font>"
        f"</para>"
    )
    qr_elements = []
    if qr_img_flowable:
        qr_elements.append(qr_img_flowable)
        qr_elements.append(Spacer(1, 2))
    qr_elements.append(Paragraph(qr_desc, cell_style))

    # Totals table
    totals_rows = [
        [Paragraph("Taxable Subtotal:", cell_style), Paragraph(f"<para align='right'>Rs. {invoice.subtotal:.2f}</para>", cell_style)],
        [Paragraph("Central GST (CGST):", cell_style), Paragraph(f"<para align='right'>+ Rs. {context['cgst_amount']:.2f}</para>", cell_style)],
        [Paragraph("State GST (SGST):", cell_style), Paragraph(f"<para align='right'>+ Rs. {context['sgst_amount']:.2f}</para>", cell_style)],
    ]
    if invoice.discount and invoice.discount > 0:
        totals_rows.append([
            Paragraph("Discount Applied:", cell_style),
            Paragraph(f"<para align='right'><font color='#dc2626'>- Rs. {invoice.discount:.2f}</font></para>", cell_style)
        ])
    totals_rows.append([
        Paragraph("<b>Grand Total:</b>", ParagraphStyle('GT', parent=cell_bold_style, fontSize=11, textColor=primary_color)),
        Paragraph(f"<para align='right'><b><font size='11' color='#4f46e5'>Rs. {invoice.grand_total:.2f}</font></b></para>", cell_bold_style)
    ])

    totals_table = Table(totals_rows, colWidths=[50 * mm, 42 * mm])
    totals_table.setStyle(TableStyle([
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 3),
        ('TOPPADDING', (0, 0), (-1, -1), 3),
        ('LINEABOVE', (0, -1), (-1, -1), 1, dark_slate),
    ]))

    summary_table = Table([
        [qr_elements, totals_table]
    ], colWidths=[92 * mm, 94 * mm])
    summary_table.setStyle(TableStyle([
        ('BOX', (0, 0), (0, 0), 0.5, border_color),
        ('BOX', (1, 0), (1, 0), 0.5, border_color),
        ('BACKGROUND', (0, 0), (0, 0), colors.white),
        ('BACKGROUND', (1, 0), (1, 0), light_bg),
        ('PADDING', (0, 0), (-1, -1), 6),
        ('VALIGN', (0, 0), (-1, -1), 'TOP'),
        ('ALIGN', (0, 0), (0, 0), 'CENTER'),
    ]))
    story.append(summary_table)
    story.append(Spacer(1, 5))

    # 6. Amount in Words Strip
    if context.get('grand_total_words'):
        words_table = Table([[Paragraph(f"<b>Amount in Words:</b> {context['grand_total_words']}", words_style)]], colWidths=[186 * mm])
        words_table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor('#eef2ff')),
            ('LINEBEFORE', (0, 0), (0, -1), 3, primary_color),
            ('PADDING', (0, 0), (-1, -1), 5),
        ]))
        story.append(words_table)
        story.append(Spacer(1, 6))

    # 7. Terms & Digital Signature
    terms_p = Paragraph(
        "<b>Terms &amp; Conditions:</b><br/>"
        "1. Goods once sold are covered under standard manufacturer warranty.<br/>"
        "2. Certified computer-generated tax invoice verified with dynamic QR code.<br/>"
        "3. Subject to jurisdiction of local commercial courts.",
        subtitle_style
    )
    sig_p = Paragraph(
        f"<para align='right'>"
        f"<font size='7' color='#059669'><b>[ DIGITALLY CERTIFIED ]</b></font><br/>"
        f"<b>For {context['business_name']}</b><br/><br/>"
        f"<font size='7.5' color='#64748b'>Authorized Signatory</font>"
        f"</para>",
        cell_style
    )
    bottom_table = Table([[terms_p, sig_p]], colWidths=[120 * mm, 66 * mm])
    bottom_table.setStyle(TableStyle([
        ('LINEABOVE', (0, 0), (-1, -1), 0.5, colors.HexColor('#cbd5e1')),
        ('TOPPADDING', (0, 0), (-1, -1), 6),
        ('VALIGN', (0, 0), (-1, -1), 'TOP'),
    ]))
    story.append(bottom_table)

    doc.build(story, canvasmaker=NumberedCanvas)
    return pdf_buffer.getvalue()


def generate_invoice_pdf_bytes(invoice, engine='auto'):
    """
    Unified entrypoint to generate certified invoice PDF bytes using either:
    - 'xhtml2pdf': HTML/CSS template to PDF
    - 'reportlab': Direct high-performance Flowable Canvas PDF
    - 'auto': Attempts xhtml2pdf first, automatically falls back to ReportLab.
    """
    engine = (engine or 'auto').lower()

    if engine == 'reportlab':
        return render_invoice_to_pdf_reportlab(invoice)
    elif engine == 'xhtml2pdf':
        return render_invoice_to_pdf_xhtml2pdf(invoice)
    else:  # auto
        try:
            if pisa:
                return render_invoice_to_pdf_xhtml2pdf(invoice)
            elif REPORTLAB_AVAILABLE:
                return render_invoice_to_pdf_reportlab(invoice)
        except Exception:
            if REPORTLAB_AVAILABLE:
                return render_invoice_to_pdf_reportlab(invoice)
            raise

    raise RuntimeError("No supported PDF engine available. Please install xhtml2pdf or reportlab.")

